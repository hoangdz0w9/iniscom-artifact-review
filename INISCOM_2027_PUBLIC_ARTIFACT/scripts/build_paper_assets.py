def reviewed_benchmark(root: Path):
    """Use only the explicitly reviewed full run; no archived-timing fallback."""
    review_dir = root / "generated" / "benchmark_review"
    review = read_json(review_dir / "review_manifest.json")
    if review.get("status") != "passed" or not review.get("full_benchmark_completed"):
        raise ValueError("A completed, independently reviewed benchmark is required")
    for script, field in (("review_benchmark_run.py", "script_sha256"), ("analyze_benchmark.py", "analyzer_sha256")):
        path = root / "scripts" / script
        if digest(path) != review[field]:
            raise ValueError(f"Benchmark review code changed: {script}; rerun the review")
        INPUTS[str(path)] = {"sha256": digest(path), "bytes": path.stat().st_size}
    for name, expected in review["file_hashes"].items():
        path = Path(name)
        if digest(path) != expected:
            raise ValueError(f"Reviewed benchmark input changed: {path}")
        INPUTS[str(path)] = {"sha256": expected, "bytes": path.stat().st_size}
    for name, expected in review["outputs"].items():
        if digest(review_dir / name) != expected:
            raise ValueError(f"Reviewed benchmark summary changed: {name}")
    seed = read_csv(review_dir / "timing_by_seed.csv")
    across = read_csv(review_dir / "timing_across_seeds.csv")
    overhead = read_csv(review_dir / "overhead_assessment.csv")
    run_quality = read_csv(Path(review["run_directory"]) / "new_run_quality.csv")
    full = across[across.regime == "primary_fullbatch"]
    ca = unique(full, model_key="cascade")
    timing = pd.DataFrame([{
        "model_key": k,
        "model_time_mean_mean_seconds": unique(full, model_key=k).mean_of_seed_means_s,
        "model_time_median_mean_seconds": unique(full, model_key=k).mean_of_seed_medians_s,
        "model_time_median_sd_across_seeds": unique(full, model_key=k).sd_seed_medians_s,
        "ratio_of_seed_aggregate_medians": unique(full, model_key=k).mean_of_seed_medians_s / ca.mean_of_seed_medians_s,
    } for k in ORDER])
    batch = seed[seed.regime == "batch_sensitivity"].copy().rename(columns={
        "batch_label": "batch_size_label", "input_n": "batch_size", "mean_s": "seconds_mean",
        "median_per_flow_us": "per_flow_latency_us_median", "mean_per_flow_us": "per_flow_latency_us_mean"})
    parallel_rows = []
    for k in ORDER:
        single = batch[(batch.model_key == k) & (batch.batch_size_label == "full")].set_index("seed").median_s
        multi = seed[(seed.regime == "parallel_fullbatch") & (seed.model_key == k)].set_index("seed").median_s
        if len(single) != 5 or set(single.index) != set(multi.index):
            raise ValueError("Parallel comparison needs the same five seeds")
        parallel_rows.append({"model_key": k, "single_seconds_mean": single.mean(),
                              "parallel_seconds_mean": multi.mean(), "parallel_speedup_mean": (single / multi).mean()})
    return review, timing, batch, pd.DataFrame(parallel_rows), overhead, run_quality


