def threshold_table_rows(policy, threshold_stats, default_cost):
    """Keep defaults in Table 2; combine all non-default metrics in Table 3."""
    main_rows = []
    for k in ORDER:
        default = unique(policy, model_key=k, policy=POLICIES[0])
        cost = unique(default_cost, model_key=k)
        if abs(default.test_F1_weighted_pct_mean - cost.F1_mean) > 1e-9 or abs(default.test_F1_weighted_pct_sd - cost.F1_sd) > 1e-9:
            raise ValueError(f"Default F1/SD disagree across tables for {k}")
        for index, (p, label) in enumerate(zip(POLICIES, POLICY_LABELS)):
            s = unique(policy, model_key=k, policy=p)
            threshold = unique(threshold_stats, model_key=k, policy=p)
            if index:
                main_rows.append(row(TEX[k] if index == 1 else "", label,
                                     pm(threshold.cutoff_mean, threshold.cutoff_sd, 4),
                                     pm(s.test_F1_weighted_pct_mean, s.test_F1_weighted_pct_sd),
                                     number(s.test_FAR_pct_mean, 2),
                                     number(s.test_Attack_recall_pct_mean, 2)))
        if k != ORDER[-1]:
            main_rows.append(r"\addlinespace")
    return main_rows


