def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_csv(path: Path) -> pd.DataFrame:
    INPUTS[str(path.resolve())] = {"sha256": digest(path), "bytes": path.stat().st_size}
    return pd.read_csv(path, float_precision="round_trip")


def read_json(path: Path) -> dict:
    INPUTS[str(path.resolve())] = {"sha256": digest(path), "bytes": path.stat().st_size}
    return json.loads(path.read_text(encoding="utf-8"))


def verify_analysis_manifest(path: Path) -> int:
    """Reject edited/stale outputs even when an old manifest says complete."""
    manifest = read_json(path)
    if manifest.get("status") != "complete":
        raise ValueError(f"Incomplete input analysis: {path}")
    entries = manifest.get("outputs", [])
    if not entries:
        raise ValueError(f"Manifest has no hashed outputs: {path}")
    checked = set()
    for item in entries:
        # Manifests from the original workstation may contain absolute paths;
        # generated outputs are all immediate siblings of their manifest.
        name = Path(item.get("file") or item["path"]).name
        candidate = path.parent / name
        if candidate in checked or not candidate.is_file() or digest(candidate) != item["sha256"]:
            raise ValueError(f"Duplicate, missing or modified analysis output: {candidate}")
        checked.add(candidate)
    if manifest.get("key_results_sha256"):
        candidate = path.parent / "key_results.json"
        if not candidate.is_file() or digest(candidate) != manifest["key_results_sha256"]:
            raise ValueError(f"Missing or modified key results: {candidate}")
    return len(checked)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")
    OUTPUTS.append(path)


def number(value: float, decimals: int = 3) -> str:
    if not math.isfinite(float(value)):
        raise ValueError(f"Refusing to put a nonfinite number in the manuscript: {value}")
    return f"{float(value):.{decimals}f}"


def pm(mean: float, sd: float, decimals: int = 3) -> str:
    return rf"${number(mean, decimals)}\pm{number(sd, decimals)}$"


def small_rate(value: float) -> str:
    return r"$<0.01$" if 0 < float(value) < .01 else number(value, 2)


def table(path: Path, caption: str, label: str, columns: str, header: str,
          rows: list[str], note: str = "", placement: str = "t") -> None:
    # Allow float pages: a large diagnostic table must not block all later tables.
    if placement in ("t", "ht"):
        placement = "!htbp"
    lines = [r"% Generated by scripts/build_paper_assets.py; do not hand-edit.",
             rf"\begin{{table}}[{placement}]", r"\centering", rf"\caption{{{caption}}}",
             rf"\label{{{label}}}", r"\small", r"\setlength{\tabcolsep}{4pt}",
             rf"\begin{{tabularx}}{{\textwidth}}{{{columns}}}",
             r"\toprule", row(header), r"\midrule", *rows, r"\bottomrule",
             r"\end{tabularx}"]
    if note:
        lines += [r"\par\smallskip", rf"\begin{{minipage}}{{\textwidth}}\footnotesize {note}\end{{minipage}}"]
    lines += [r"\end{table}"]
    write(path, "\n".join(lines))


def row(*cells: str) -> str:
    return " & ".join(cells) + r" \\"


def unique(frame: pd.DataFrame, **filters) -> pd.Series:
    for key, value in filters.items():
        frame = frame[frame[key] == value]
    if len(frame) != 1:
        raise ValueError(f"Expected exactly one row for {filters}; found {len(frame)}")
    return frame.iloc[0]


def band_rates(bands: pd.DataFrame, audit: pd.DataFrame) -> pd.DataFrame:
    keys = ["model_key", "seed", "split"]
    result = bands.merge(audit[keys + ["n_normal", "n_attack"]], on=keys, how="left", validate="one_to_one")
    if result[["n_normal", "n_attack"]].isna().any().any() or (result[["n_normal", "n_attack"]] <= 0).any().any():
        raise ValueError("Missing/invalid exact class denominators")
    for name in ("normal", "attack"):
        if (result[f"{name}_rows_reclassified"] > result[f"n_{name}"]).any():
            raise ValueError("Band count exceeds its class denominator")
        result[f"{name}_band_pct"] = 100 * result[f"{name}_rows_reclassified"] / result[f"n_{name}"]
    return result


def merge_sparse_bins(frame: pd.DataFrame, minimum_calls: int = 10) -> pd.DataFrame:
    """Merge adjacent positive bins using counts only; preserve zero-stage calls.

    Recompute within-seed errors from call-weighted means, NOT mean old errors.
    Final figure averages represented seeds equally, as before.
    """
    order = ["0", "1", "2-4", "5-16", "17-64", "65+"]
    if minimum_calls < 1 or set(frame.stage3_bin) - set(order):
        raise ValueError("Invalid minimum support or unknown Stage-3 bin")
    if frame.duplicated(["seed", "input_n", "stage3_bin"]).any() or (frame.n_calls <= 0).any():
        raise ValueError("Duplicate bin/seed or invalid call count")
    rows = []
    for size, selected in frame.groupby("input_n"):
        counts = selected.groupby("stage3_bin").n_calls.sum()
        groups, pending, count = [], [], 0
        for name in order[1:]:
            if name not in counts:
                continue
            pending.append(name)
            count += int(counts[name])
            if count >= minimum_calls:
                groups.append(pending)
                pending, count = [], 0
        if pending:
            if not groups:
                raise ValueError("Too few positive-stage calls for minimum support")
            groups[-1].extend(pending)
        if "0" in counts:
            groups.insert(0, ["0"])
        for group in groups:
            low = group[0].split("-")[0]
            high = group[-1].split("-")[-1]
            label = group[0] if len(group) == 1 else (low + "+" if high.endswith("+") else low + "-" + high)
            for seed, values in selected[selected.stage3_bin.isin(group)].groupby("seed"):
                calls = int(values.n_calls.sum())
                measured = float(np.average(values.measured_mean_s, weights=values.n_calls))
                predicted = float(np.average(values.predicted_mean_s, weights=values.n_calls))
                if measured <= 0:
                    raise ValueError("Invalid measured latency")
                rows.append({"seed": int(seed), "input_n": int(size), "stage3_bin": label,
                             "source_bins": "|".join(group), "n_calls": calls,
                             "stage3_n_mean": float(np.average(values.stage3_n_mean, weights=values.n_calls)),
                             "measured_mean_s": measured, "predicted_mean_s": predicted,
                             "signed_error_pct": 100 * (predicted - measured) / measured})
    merged = pd.DataFrame(rows)
    if int(merged.n_calls.sum()) != int(frame.n_calls.sum()):
        raise ValueError("Bin merging lost calls")
    # Zero is not merged with positive work, even if sparse in another dataset.
    for (seed, size), group in frame.groupby(["seed", "input_n"]):
        result = merged[(merged.seed == seed) & (merged.input_n == size)]
        for metric in ("measured_mean_s", "predicted_mean_s", "stage3_n_mean"):
            if not np.isclose(np.average(group[metric], weights=group.n_calls), np.average(result[metric], weights=result.n_calls), atol=1e-12, rtol=0):
                raise ValueError("Bin merging changed aggregate call means")
    return merged


